"use strict";
const {chromium}=require(process.argv[2]);
const assert=require('node:assert/strict');
const path=require('node:path');
(async()=>{
  const browser=await chromium.launch({executablePath:process.argv[3],headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[],starts={},responses=[];
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>{const p=new URL(r.url()).pathname;if(!starts[p])starts[p]=Date.now();});
  page.on('response',r=>responses.push(r));
  await page.route('**/api/v2/game-names*',async route=>{await new Promise(r=>setTimeout(r,700));await route.continue();});
  try{
    const opening=Date.now();await page.goto(process.argv[5]);
    await page.waitForFunction(()=>document.getElementById('sourcebar')?.innerText.includes('Свой скан:'));
    await page.getByRole('heading',{name:'Возможности',exact:true}).waitFor();
    assert.ok(Date.now()-opening<2500,'Startup must not wait for the market database');
    assert.ok(starts['/api/v2/overview']-starts['/api/v2/game-names']<500,'Overview must not wait for names to download');
    await page.locator('[data-page="vendor"]').click();
    await page.locator('#vendor-section').waitFor();
    await page.getByText('1–2 из 2',{exact:true}).waitFor();
    assert.equal(await page.locator('#vendor-section tbody tr').count(),2);
    assert.ok((await page.locator('#vendor-section').innerText()).includes('Рядом с ценой NPC'));
    assert.ok((await page.locator('#vendor-section tbody tr').first().innerText()).includes('+1%'));
    await page.getByRole('checkbox',{name:'Скрыть нестакаемые'}).check();
    await page.getByText('1–1 из 1',{exact:true}).waitFor();
    await page.getByRole('checkbox',{name:'Скрыть нестакаемые'}).uncheck();
    await page.getByText('1–2 из 2',{exact:true}).waitFor();
    await page.locator('#vendor-filters [name="sort"]').selectOption('price');
    await page.locator('#vendor-filters [name="order"]').selectOption('desc');
    await page.locator('#vendor-filters button[type="submit"]').click();
    await page.waitForFunction(()=>document.querySelector('#vendor-section tbody tr td:nth-child(2)')?.textContent.includes('2 с 4 м'));
    await page.locator('#vendor-filters [name="max_markup"]').fill('1.5');
    await page.locator('#vendor-filters button[type="submit"]').click();
    await page.getByText('1–1 из 1',{exact:true}).waitFor();
    await page.locator('#vendor-filters [name="max_markup"]').fill('');
    await page.locator('#vendor-filters button[type="submit"]').click();
    await page.getByText('1–2 из 2',{exact:true}).waitFor();
    await page.locator('[data-vendor-reset]').click();
    await page.getByText('1–2 из 2',{exact:true}).waitFor();
    await page.locator('#vendor-filters [name="min_markup"]').fill('20');
    await page.locator('#vendor-filters button[type="submit"]').click();
    assert.equal(await page.locator('#vendor-filters [name="min_markup"]').evaluate(e=>e.validity.customError),true);
    assert.equal(await page.locator('#vendor-section tbody tr').count(),2,'Invalid range must preserve the editable table');
    await page.locator('#vendor-filters [name="min_markup"]').fill('');
    assert.equal(await page.locator('#vendor-filters [name="min_markup"]').evaluate(e=>e.validity.customError),false);
    await page.locator('[data-vendor-sort="markup"]').click();
    await page.locator('[data-vendor-sort="markup"]').click();
    await page.waitForFunction(()=>document.querySelector('#vendor-section tbody tr td:nth-child(4)')?.textContent.includes('+2%'));
    await page.screenshot({path:path.join(process.argv[4],'vendor-desktop.png'),fullPage:true});
    assert.equal((await page.request.post(process.argv[5]+'/fixture/lock-market')).status(),200);
    const navigating=Date.now();
    await page.locator('[data-page="opportunities"]').click();
    await page.getByRole('heading',{name:'Возможности',exact:true}).waitFor();
    await page.locator('[data-page="vendor"]').click();
    await page.locator('#vendor-section').waitFor();
    assert.ok(Date.now()-navigating<2500,'Navigation must not wait for a 4-second market lock');
    const names=responses.find(r=>new URL(r.url()).pathname.endsWith('/game-names'));
    assert.equal(await names.headerValue('content-encoding'),'gzip');
    await page.getByRole('checkbox',{name:'Скрыть нестакаемые'}).check();
    await page.getByText('1–1 из 1',{exact:true}).waitFor();
    await page.reload();
    await page.waitForFunction(()=>document.getElementById('sourcebar')?.innerText.includes('Свой скан:'));
    assert.ok(responses.some(r=>r.url().includes('/game-names?revision=')),'Reload must reuse cached catalog revision');
    await page.setViewportSize({width:390,height:844});
    await page.locator('[data-page="vendor"]').click();
    await page.locator('#vendor-section').waitFor();
    assert.equal(await page.getByRole('checkbox',{name:'Скрыть нестакаемые'}).isChecked(),true);
    await page.getByText('1–1 из 1',{exact:true}).waitFor();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:path.join(process.argv[4],'vendor-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({vendor_page:'passed',item_rows:2,editable_markup:true,table_sort:true,parallel_startup:true,compressed_names:true,catalog_reused:true,mobile:true,navigation_while_market_locked:true}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
