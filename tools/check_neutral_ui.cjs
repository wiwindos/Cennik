"use strict";
const {chromium}=require(process.argv[2]);
const assert=require('node:assert/strict');
const path=require('node:path');
(async()=>{
  const browser=await chromium.launch({executablePath:process.argv[3],headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  try{
    await page.goto(process.argv[5]);
    await page.waitForFunction(()=>document.getElementById('sourcebar')?.innerText.includes('Свой скан:'));
    const opening=Date.now();
    await page.locator('[data-page="neutral"]').click();
    await page.locator('#neutral-section').waitFor();
    assert.ok(Date.now()-opening<2000,'Neutral filters must open before the market lock is released');
    await page.locator('#neutral-filters input[name="q"]').waitFor();
    await page.getByText('1–1 из 1',{exact:true}).waitFor();
    assert.equal(await page.locator('[data-neutral-item]').count(),1);
    const liveLiquidity=await page.locator('#neutral-results .neutral-liquidity').innerText();
    assert.ok(liveLiquidity.includes('2,5 продаж/сутки')&&liveLiquidity.includes('все варианты')&&liveLiquidity.includes('AHledger'));
    const liquidity=await page.evaluate(()=>{
      const base={sales_per_day:'2.500000',sales_source:'AHL1',sales_observed_at:'2026-11-16T10:00:00Z'};
      const data={as_of:'2026-11-16T10:30:00Z',stale_after_seconds:3600};
      return {fresh:window.CennikNeutral.liquidity(base,data),stale:window.CennikNeutral.liquidity(base,{...data,as_of:'2026-11-16T12:00:00Z'}),zero:window.CennikNeutral.liquidity({...base,sales_per_day:'0'},data)};
    });
    assert.ok(liquidity.fresh.includes('2,5 продаж/сутки')&&liquidity.fresh.includes('AHledger'));
    assert.ok(!liquidity.fresh.includes('Оценка устарела'));
    assert.ok(liquidity.stale.includes('Оценка устарела'));
    assert.ok(liquidity.zero.includes('0 продаж/сутки')&&!liquidity.zero.includes('неизвестна'));
    await page.locator('[data-neutral-item]').click();
    await page.locator('#neutral-detail table tbody tr').first().waitFor();
    assert.equal(await page.locator('#neutral-detail table tbody tr').count(),2);
    assert.ok((await page.locator('#neutral-detail').innerText()).includes('36 м'));
    await page.screenshot({path:path.join(process.argv[4],'neutral-desktop.png'),fullPage:true});
    await page.locator('[data-neutral-mode="all"]').click();
    await page.getByText('1–2 из 2',{exact:true}).waitFor();
    assert.ok((await page.locator('#neutral-results').innerText()).includes('Нет цены продажи'),await page.locator('#neutral-results').innerText());
    await page.locator('#neutral-filters [name="budget"]').fill('0.002');
    await page.locator('#neutral-filters button[type="submit"]').click();
    await page.locator('[data-neutral-item]').first().click();
    await page.getByText('Закупка 4 шт.',{exact:true}).waitFor();
    await page.locator('#neutral-filters [name="q"]').fill('2589');
    assert.equal((await page.request.post(process.argv[5]+'/fixture/lock-market')).status(),200);
    const filtering=Date.now();
    await page.locator('#neutral-filters button[type="submit"]').click();
    await page.getByText('1–1 из 1',{exact:true}).waitFor();
    assert.ok(Date.now()-filtering<2500,'Prepared comparison must filter while the market is locked');
    // Automatic refresh preserves a draft filter and updates the table.
    await page.locator('#neutral-filters [name="q"]').fill('не потерять ввод');
    await page.evaluate(()=>{window.CennikNeutral.lastPoll=0;return window.CennikNeutral.poll();});
    assert.equal(await page.locator('#neutral-filters [name="q"]').inputValue(),'не потерять ввод');
    await page.locator('[data-neutral-reset]').click();
    await page.getByText('1–2 из 2',{exact:true}).waitFor();
    await page.locator('#neutral-filters [name="sort"]').selectOption('sales');
    await page.locator('#neutral-filters [name="order"]').selectOption('asc');
    await page.locator('#neutral-filters [name="min_sales"]').fill('0');
    await page.locator('#neutral-filters [name="max_sales"]').fill('0');
    await page.locator('#neutral-filters button[type="submit"]').click();
    await page.getByText('0–0 из 0',{exact:true}).waitFor();
    await page.locator('[data-neutral-reset]').click();
    await page.getByText('1–2 из 2',{exact:true}).waitFor();
    await page.locator('#neutral-filters [name="price_basis"]').selectOption('sale');
    await page.locator('#neutral-filters [name="min_price"]').fill('0.0009');
    await page.locator('#neutral-filters [name="sort"]').selectOption('sale_price');
    await page.locator('#neutral-filters button[type="submit"]').click();
    await page.getByText('1–1 из 1',{exact:true}).waitFor();
    await page.locator('#neutral-filters [name="max_roi"]').fill('80');
    await page.locator('#neutral-filters button[type="submit"]').click();
    await page.getByText('0–0 из 0',{exact:true}).waitFor();
    await page.locator('[data-neutral-reset]').click();
    await page.getByText('1–2 из 2',{exact:true}).waitFor();
    assert.equal(await page.locator('#neutral-filters [name="min_sales"]').inputValue(),'');
    assert.equal(await page.locator('#neutral-filters [name="max_roi"]').inputValue(),'');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(process.argv[4],'neutral-mobile.png'),fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    assert.equal(await page.locator('#neutral-section [data-snipe-item],#neutral-section [data-action="publish"]').count(),0);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({navigation:'passed',liquidity:'passed',details:'passed',filters:'passed',auto_refresh:'passed',cold_open:'passed',locked_market_filter:'passed',mobile:'passed',console_errors:errors}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
